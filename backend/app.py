@app.post("/api/auth/register")
def register(body: Credentials, request: Request):
    email = body.email.strip().lower()
    if not re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+", email):
        raise HTTPException(400, "أدخل بريدًا إلكترونيًا صحيحًا")
    initial_role = "data_analyst" if INITIAL_ANALYST_EMAIL and email == INITIAL_ANALYST_EMAIL else "officer"
    name = body.name.strip() or email.split("@", 1)[0]
    try:
        with db() as connection:
            user = connection.execute(
                "INSERT INTO app_users(email,name,password_hash,role) VALUES(%s,%s,%s,%s) RETURNING id,email,name,role",
                (email, name, password_hash(body.password), initial_role),
            ).fetchone()
            sync_database_role(connection, user["id"], user["role"])
    except psycopg.IntegrityError:
        raise HTTPException(409, "هذا البريد مسجل مسبقًا") from None
    request.session["user_id"] = user["id"]
    return dict(user)


@app.post("/api/auth/login")
def login(body: Credentials, request: Request):
    email = body.email.strip().lower()
    with db() as connection:
        user = connection.execute("SELECT * FROM app_users WHERE lower(email)=%s", (email,)).fetchone()
    if not user or not user["active"] or not verify_password(body.password, user["password_hash"]):
        raise HTTPException(401, "البريد أو كلمة المرور غير صحيحة")
    request.session.clear()
    request.session["user_id"] = user["id"]
    return {"id": user["id"], "email": user["email"], "name": user["name"], "role": user["role"]}


