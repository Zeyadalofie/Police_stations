def sync_database_role(connection, user_id: int, app_role: str, db_user: str | None = None):
    """Give each account a non-login DB role so row policies bind to current_user."""
    db_user = db_user or connection.execute("SELECT current_user").fetchone()["current_user"]
    account_role = f"police_app_user_{int(user_id)}"
    exists = connection.execute("SELECT 1 FROM pg_roles WHERE rolname=%s", (account_role,)).fetchone()
    if not exists:
        connection.execute(sql.SQL("CREATE ROLE {} NOLOGIN INHERIT").format(sql.Identifier(account_role)))
    for database_role in SQL_DATABASE_ROLES.values():
        connection.execute(sql.SQL("REVOKE {} FROM {}").format(sql.Identifier(database_role), sql.Identifier(account_role)))
    connection.execute(
        sql.SQL("GRANT {} TO {}").format(sql.Identifier(SQL_DATABASE_ROLES[app_role]), sql.Identifier(account_role))
    )
    connection.execute(
        sql.SQL("GRANT {} TO {}").format(sql.Identifier(account_role), sql.Identifier(db_user))
    )


def db():
    if not DATABASE_URL:
        raise RuntimeError("Set NEON_ADMIN_DATABASE_URL in the local .env file.")
    return psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=15)


def initialize_database():
    with db() as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS app_users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL UNIQUE,
                name TEXT NOT NULL,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'officer'
                    CHECK (role IN ('data_analyst','police_commander','officer','mayor')),
                active BOOLEAN NOT NULL DEFAULT TRUE,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)
        connection.execute("ALTER TABLE app_users ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'officer'")
        connection.execute("ALTER TABLE app_users ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE")
        connection.execute("""
            CREATE TABLE IF NOT EXISTS operation_records (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title TEXT NOT NULL,
                category TEXT NOT NULL,
                region TEXT NOT NULL,
                priority TEXT NOT NULL DEFAULT 'عادي' CHECK (priority IN ('منخفض','عادي','مرتفع','عاجل')),
                status TEXT NOT NULL DEFAULT 'قيد المتابعة' CHECK (status IN ('قيد المتابعة','جارٍ التنفيذ','مكتملة')),
                response_minutes INTEGER CHECK (response_minutes IS NULL OR response_minutes >= 0),
                occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                created_by BIGINT NOT NULL REFERENCES app_users(id)
            )
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS role_change_log (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                changed_by BIGINT NOT NULL REFERENCES app_users(id),
                target_user_id BIGINT NOT NULL REFERENCES app_users(id),
                previous_role TEXT NOT NULL,
                new_role TEXT NOT NULL,
                changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)
        connection.execute("CREATE SCHEMA IF NOT EXISTS analyst_workspace")

        if INITIAL_ANALYST_EMAIL:
            connection.execute(
                "UPDATE app_users SET role='officer' WHERE role='data_analyst' AND lower(email)<>%s",
                (INITIAL_ANALYST_EMAIL,),
            )
            connection.execute(
                "UPDATE app_users SET role='data_analyst' WHERE lower(email)=%s",
                (INITIAL_ANALYST_EMAIL,),
            )

        connection.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS app_users_single_data_analyst
            ON app_users (role) WHERE role='data_analyst'
        """)

        db_user = connection.execute("SELECT current_user").fetchone()["current_user"]
        role_names = tuple(SQL_DATABASE_ROLES.values())
        for role_name in role_names:
            exists = connection.execute("SELECT 1 FROM pg_roles WHERE rolname=%s", (role_name,)).fetchone()
            if not exists:
                connection.execute(sql.SQL("CREATE ROLE {} NOLOGIN").format(sql.Identifier(role_name)))
            connection.execute(
                sql.SQL("GRANT {} TO {}").format(sql.Identifier(role_name), sql.Identifier(db_user))
            )
            connection.execute(sql.SQL("GRANT USAGE ON SCHEMA public TO {}").format(sql.Identifier(role_name)))

        connection.execute("GRANT SELECT ON TABLE operation_records TO police_app_officer_sql, police_app_commander_sql")
        connection.execute("GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE operation_records TO police_app_analyst_sql")
        connection.execute("GRANT USAGE, SELECT ON SEQUENCE operation_records_id_seq TO police_app_analyst_sql")
        connection.execute("GRANT USAGE, CREATE ON SCHEMA analyst_workspace TO police_app_analyst_sql")
        connection.execute("ALTER TABLE operation_records ENABLE ROW LEVEL SECURITY")
        connection.execute("DROP POLICY IF EXISTS police_officer_own_records ON operation_records")
        connection.execute("DROP POLICY IF EXISTS police_commander_all_records ON operation_records")
        connection.execute("DROP POLICY IF EXISTS police_analyst_all_records ON operation_records")
        connection.execute("""
            CREATE POLICY police_officer_own_records ON operation_records
            FOR SELECT TO PUBLIC
            USING (
                current_user ~ '^police_app_user_[0-9]+$'
                AND created_by = SUBSTRING(current_user FROM '[0-9]+$')::BIGINT
            )
        """)
        connection.execute("""
            CREATE POLICY police_commander_all_records ON operation_records
            FOR SELECT TO police_app_commander_sql USING (TRUE)
        """)
        connection.execute("""
            CREATE POLICY police_analyst_all_records ON operation_records
            FOR ALL TO police_app_analyst_sql USING (TRUE) WITH CHECK (TRUE)
        """)
        for account in connection.execute("SELECT id,role FROM app_users").fetchall():
            sync_database_role(connection, account["id"], account["role"], db_user)


@asynccontextmanager
async def lifespan(_: FastAPI):
    initialize_database()
    yield


