"""PostgreSQL schema initialization for the application."""


SCHEMA_STATEMENTS = (
    """
    CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email TEXT NOT NULL UNIQUE,
        name TEXT NOT NULL,
        password_hash TEXT,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS social_accounts (
        provider TEXT NOT NULL,
        subject TEXT NOT NULL,
        user_id BIGINT NOT NULL REFERENCES users(id),
        PRIMARY KEY (provider, subject)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS connections (
        user_id BIGINT PRIMARY KEY REFERENCES users(id),
        ai TEXT,
        drive TEXT,
        s3 TEXT,
        active_storage TEXT DEFAULT 'local'
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS reports (
        user_id BIGINT PRIMARY KEY REFERENCES users(id),
        data TEXT NOT NULL,
        filename TEXT NOT NULL,
        updated_at TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS storage_paths (
        user_id BIGINT PRIMARY KEY REFERENCES users(id),
        drive_path TEXT NOT NULL DEFAULT '',
        s3_prefix TEXT NOT NULL DEFAULT ''
    )
    """,
)


def init_db(connection_factory):
    """Create missing application tables without changing existing data."""
    with connection_factory() as connection:
        for statement in SCHEMA_STATEMENTS:
            connection.execute(statement)
